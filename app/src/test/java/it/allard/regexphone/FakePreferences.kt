package it.allard.regexphone

import android.content.SharedPreferences

/**
 * SharedPreferences over a plain map, enough of it for RuleRepository. The
 * real one needs an Android runtime, which unit tests do not have.
 */
class FakePreferences : SharedPreferences {
    private val values = HashMap<String, Any>()

    override fun getAll(): Map<String, *> = HashMap(values)
    override fun contains(key: String): Boolean = key in values
    override fun getString(key: String, defValue: String?): String? = values[key] as String? ?: defValue
    override fun getLong(key: String, defValue: Long): Long = values[key] as Long? ?: defValue
    override fun getInt(key: String, defValue: Int): Int = values[key] as Int? ?: defValue
    override fun getFloat(key: String, defValue: Float): Float = values[key] as Float? ?: defValue
    override fun getBoolean(key: String, defValue: Boolean): Boolean = values[key] as Boolean? ?: defValue

    @Suppress("UNCHECKED_CAST")
    override fun getStringSet(key: String, defValues: Set<String>?): Set<String>? =
        values[key] as Set<String>? ?: defValues

    override fun edit(): SharedPreferences.Editor = FakeEditor()

    override fun registerOnSharedPreferenceChangeListener(
        listener: SharedPreferences.OnSharedPreferenceChangeListener,
    ) = Unit

    override fun unregisterOnSharedPreferenceChangeListener(
        listener: SharedPreferences.OnSharedPreferenceChangeListener,
    ) = Unit

    private inner class FakeEditor : SharedPreferences.Editor {
        // A null value stands for a removal.
        private val pending = LinkedHashMap<String, Any?>()
        private var clear = false

        private fun put(key: String, value: Any?) = apply { pending[key] = value }

        override fun putString(key: String, value: String?) = put(key, value)
        override fun putStringSet(key: String, values: Set<String>?) = put(key, values?.toSet())
        override fun putInt(key: String, value: Int) = put(key, value)
        override fun putLong(key: String, value: Long) = put(key, value)
        override fun putFloat(key: String, value: Float) = put(key, value)
        override fun putBoolean(key: String, value: Boolean) = put(key, value)
        override fun remove(key: String) = put(key, null)
        override fun clear() = apply { clear = true }

        override fun commit(): Boolean {
            if (clear) values.clear()
            for ((key, value) in pending) {
                if (value == null) values.remove(key) else values[key] = value
            }
            return true
        }

        override fun apply() {
            commit()
        }
    }
}
